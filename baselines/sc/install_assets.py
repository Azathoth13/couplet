#!/usr/bin/env python3
"""Install frozen SC contracts and regenerate exact plaintext reference trajectories.

1B/3B consume the SC linear archives generated by tools/models. 8B additionally
applies the frozen residual/value rotations; merely copying QuaRot weights is
not a valid 8B SC baseline. No FHE or GPU computation is performed here.
"""
from __future__ import annotations

import argparse
import gc
import hashlib
import json
import os
from pathlib import Path
import shutil
import sys

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))


def sha256(path):
    h = hashlib.sha256()
    with Path(path).open('rb') as stream:
        for block in iter(lambda: stream.read(8 << 20), b''):
            h.update(block)
    return h.hexdigest()


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--model', choices=('1b', '3b', '8b'), required=True)
    p.add_argument('--data-root', type=Path, required=True)
    p.add_argument('--checkpoint', type=Path, required=True)
    p.add_argument('--fixture-dir', type=Path)
    args = p.parse_args(argv)
    import numpy as np
    from baselines.sc.rotation import OrthogonalRotation, convert_weights
    from llama3fhe.application.checkpoint import CheckpointMetadata, WeightLoader, load_layer_weights
    data = args.data_root.expanduser().resolve()
    checkpoint = args.checkpoint.expanduser().resolve()
    chain = data / 'sc' / args.model / 'chain'
    fixtures = args.fixture_dir or data / 'fixtures' / args.model
    template = Path(__file__).resolve().parent / 'assets' / args.model / 'chain'
    config = CheckpointMetadata.from_json(checkpoint / 'config.json')
    count = {'1b': 16, '3b': 28, '8b': 32}[args.model]
    if config.num_hidden_layers != count:
        raise ValueError('model/checkpoint layer count differs')
    manifest = json.loads((template / 'chain-manifest.json').read_text())
    chain.mkdir(parents=True, exist_ok=True)
    for path in template.glob('layer-*/calibration.json'):
        target = chain / path.relative_to(template)
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, target)
    manifest['source_checkpoint'] = str(checkpoint)
    manifest['source_config_sha256'] = sha256(checkpoint / 'config.json')
    manifest['plain_inputs'] = 'plain_inputs.npz'
    manifest['plain_final_hidden'] = 'plain_final_hidden.npy'
    if args.model == '8b':
        manifest['terminal']['checkpoint'] = str(checkpoint)
    manifest['release_preparation'] = dict(
        implementation='SC exact NumPy reference',
        frozen_contracts='baselines/sc/assets/' + args.model + '/chain',
        checkpoint_config_sha256=manifest['source_config_sha256'],
        note='Generated asset hashes are recorded below; historical NPZ archive hashes are not reused.')
    # The frozen benchmark begins from the official embeddings in the QuaRot
    # residual basis, before any polynomial approximation is applied.
    trajectory = fixtures / 'hidden_trajectory.npz'
    with np.load(trajectory, allow_pickle=False) as z:
        x = np.asarray(z['hidden_0'], dtype=np.float64)
        input_ids = np.asarray(z['input_ids']).reshape(-1).tolist()
    expected_ids = manifest.get('input_ids', manifest.get('inputs', {}).get('token_ids'))
    if expected_ids != input_ids or len(input_ids) != 128:
        raise ValueError('fixtures do not match the frozen 128-token SC input')
    provider = Path(__file__).resolve().parent / 'providers' / f'llama{args.model}'
    os.environ['SYLPH_CHAIN'] = str(chain)
    os.environ['SYLPH_ROOT'] = str(provider)
    os.environ['SYLPH_PUBLIC_PREFIX'] = '0'
    os.environ['SYLPH_HEAD24_COMPACT'] = '1' if args.model == '3b' else '0'
    sys.path.insert(0, str(provider))
    from sylph_easy.layer import plain
    from sylph_easy.chain.manifest import load
    residual = value = None
    if args.model == '8b':
        residual = OrthogonalRotation.generate(config.hidden_size, int(manifest['rotation_seed']))
        value = OrthogonalRotation.generate(config.hidden_size // config.num_attention_heads,
                                             int(manifest['rotation_seed']) + 10000)
        x = residual.apply(x)
    references = {}
    records = []
    with WeightLoader(checkpoint, tensor_dtype=np.float64) as loader:
        for index in range(count):
            entry = dict(layer=index, calibration=str(chain / f'layer-{index:02d}/calibration.json'),
                         weights=str(chain / f'layer-{index:02d}/weights.npz'))
            if args.model == '8b':
                layer = load_layer_weights(loader, index, metadata=config)
                raw = dict(q=layer.q_proj, k=layer.k_proj, v=layer.v_proj, o=layer.o_proj,
                           gate=layer.gate_proj, up=layer.up_proj, down=layer.down_proj,
                           attention_norm=layer.input_layernorm, ffn_norm=layer.post_attention_layernorm)
                weights = convert_weights(raw, residual, value, hidden=config.hidden_size,
                    heads=config.num_attention_heads, kv_heads=config.num_key_value_heads,
                    head_dim=config.hidden_size // config.num_attention_heads)
                empty = np.zeros((0, config.num_key_value_heads, config.hidden_size // config.num_attention_heads))
                weights.update(residual_signs=residual.signs, residual_permutation=residual.permutation,
                               value_signs=value.signs, value_permutation=value.permutation,
                               public_keys=empty, public_values=empty,
                               raw_public_keys=empty, raw_public_values=empty)
                np.savez(entry['weights'], **weights)
                del raw, layer, weights
            w, cal = load(entry, staged=False)
            references[f'layer{index:02d}'] = x.copy()
            x, _ = plain.layer_from_calibration(x, w, cal)
            records.append(dict(layer=index, weights_sha256=sha256(entry['weights']),
                                calibration_sha256=sha256(entry['calibration'])))
            del w, cal
            gc.collect()
            print(json.dumps(records[-1]), flush=True)
        if args.model != '8b':
            head = loader.get('lm_head.weight', out_dtype=np.float32)
            np.save(chain / 'lm_head.npy', head)
    references['final'] = x
    np.savez(chain / 'plain_inputs.npz', **references)
    np.save(chain / 'plain_final_hidden.npy', x)
    if residual is not None:
        np.save(chain / 'client-plain-final-hidden.npy', residual.apply(x, inverse=True))
    manifest['release_preparation'].update(layers=records,
        plain_inputs_sha256=sha256(chain / 'plain_inputs.npz'))
    # Driver source preflight and terminal evaluation consume this relocated manifest.
    (chain / 'chain-manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    print(json.dumps({'model': args.model, 'chain': str(chain), 'layers': count,
                      'plain_inputs_sha256': manifest['release_preparation']['plain_inputs_sha256']}), flush=True)


if __name__ == '__main__':
    main()
